/** The caption's width of `text` in px, kerning aside (a little over, as it should be for a guard). */
export function captionWidth(text: string): number {
  let width = 0;
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    width += WIDTHS[code] ?? (code >= 0x2e80 ? 11 : 8);
  }
  return width;
}
